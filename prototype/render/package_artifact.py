"""Package the built Sphinx guide page as one self-contained artifact page."""

import pathlib
import re

root = pathlib.Path(__file__).parent
page = root / "docs/_build/html/migration_guides/itk_6_migration_guide.html"
html = page.read_text()

css = []
for href in re.findall(r'<link rel="stylesheet"[^>]*href="([^"]+)"', html):
    path = (page.parent / href.split("?")[0]).resolve()
    if path.exists():
        css.append(f"/* {path.name} */\n" + path.read_text())

body = html[html.index("<body") : html.rindex("</body>")]
body = body[body.index(">") + 1 :]
body = re.sub(r"<script\b.*?</script>", "", body, flags=re.S)
body = re.sub(r'href="(\.\./)?(index|genindex|search)\.html[^"]*"', 'href="#"', body)

banner = (
    '<div style="background:#fff4d6;color:#4a3800;border-bottom:1px solid #e0c870;'
    'padding:10px max(16px, env(safe-area-inset-left, 0px));font:14px system-ui,sans-serif">'
    "<strong>Prototype.</strong> Generated by a Sphinx extension from 8 YAML migration records "
    "(two of them released, six unreleased). Real ITK entries; the layout is the question."
    "</div>"
)
out = root / "itk6_guide_prototype.html"
out.write_text(
    "<title>ITK 6 Migration Guide Prototype</title>\n"
    '<meta name="claude:viewport-fit-sides" content="cover">\n'
    "<style>\n"
    + "\n".join(css)
    + "\nbody{background:var(--color-background-primary,#fff)}\n</style>\n"
    + banner
    + body
)
print(out, len(out.read_text()) // 1024, "KiB,", len(css), "stylesheets inlined")
